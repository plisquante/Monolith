package java.lang;

import java.lang.invoke.MethodType;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.function.Consumer;
import java.util.function.Function;
import java.util.stream.Stream;

/**
 * monolith overlay of java.lang.StackWalker over the native image's precise frame chain (every
 * compiled method keeps a frame record with its class, name, descriptor, file and current line).
 * Reflection frames (java.lang.reflect.Method/Constructor, jdk.internal.reflect.*) and hidden
 * frames (lambda/proxy/method-handle implementation classes generated by the transpiler) are
 * filtered as by the JDK unless SHOW_REFLECT_FRAMES / SHOW_HIDDEN_FRAMES is given.
 */
public final class StackWalker {
    public enum Option {
        RETAIN_CLASS_REFERENCE,
        DROP_METHOD_INFO,
        SHOW_REFLECT_FRAMES,
        SHOW_HIDDEN_FRAMES
    }

    enum ExtendedOption {
        LOCALS_AND_OPERANDS
    }

    public interface StackFrame {
        String getClassName();

        String getMethodName();

        Class<?> getDeclaringClass();

        default MethodType getMethodType() {
            throw new UnsupportedOperationException();
        }

        default String getDescriptor() {
            throw new UnsupportedOperationException();
        }

        int getByteCodeIndex();

        String getFileName();

        int getLineNumber();

        boolean isNativeMethod();

        StackTraceElement toStackTraceElement();
    }

    static final EnumSet<Option> DEFAULT_EMPTY_OPTION = EnumSet.noneOf(Option.class);
    private static final StackWalker DEFAULT_WALKER = new StackWalker(DEFAULT_EMPTY_OPTION);

    private final Set<Option> options;
    final boolean retainClassRef;

    private StackWalker(Set<Option> options) {
        this.options = options;
        this.retainClassRef = options.contains(Option.RETAIN_CLASS_REFERENCE);
    }

    public static StackWalker getInstance() {
        return DEFAULT_WALKER;
    }

    public static StackWalker getInstance(Option option) {
        return new StackWalker(EnumSet.of(Objects.requireNonNull(option)));
    }

    public static StackWalker getInstance(Set<Option> options) {
        return options.isEmpty() ? DEFAULT_WALKER : new StackWalker(EnumSet.copyOf(options));
    }

    public static StackWalker getInstance(Set<Option> options, int estimateDepth) {
        if (estimateDepth <= 0) throw new IllegalArgumentException("estimateDepth must be > 0");
        return getInstance(options);
    }

    static StackWalker newInstance(Set<Option> options, ExtendedOption extendedOption) {
        return getInstance(options);
    }

    boolean hasOption(Option option) {
        return options.contains(option);
    }

    /** {Class[] classes, String[] names, String[] descriptors, String[] files, int[] lines}, innermost first. */
    private static native Object[] frames0();

    private static final class Frame implements StackFrame {
        private final StackWalker walker;
        private final Class<?> cls;
        private final String name, desc, file;
        private final int line;

        Frame(StackWalker walker, Class<?> cls, String name, String desc, String file, int line) {
            this.walker = walker;
            this.cls = cls;
            this.name = name;
            this.desc = desc;
            this.file = file;
            this.line = line;
        }

        public String getClassName() {
            return cls.getName();
        }

        public String getMethodName() {
            if (walker.hasOption(Option.DROP_METHOD_INFO)) throw new UnsupportedOperationException("method info dropped");
            return name;
        }

        public Class<?> getDeclaringClass() {
            if (!walker.retainClassRef) throw new UnsupportedOperationException("No access to RETAIN_CLASS_REFERENCE");
            return cls;
        }

        public MethodType getMethodType() {
            getDeclaringClass();
            return MethodType.fromMethodDescriptorString(desc, cls.getClassLoader());
        }

        public String getDescriptor() {
            return desc;
        }

        public int getByteCodeIndex() {
            return -1; // the native image keeps line numbers, not bytecode indices
        }

        public String getFileName() {
            return file;
        }

        public int getLineNumber() {
            return line > 0 ? line : -1;
        }

        public boolean isNativeMethod() {
            return false;
        }

        public StackTraceElement toStackTraceElement() {
            return new StackTraceElement(cls.getName(), name, file, line > 0 ? line : -1);
        }

        public String toString() {
            return toStackTraceElement().toString();
        }
    }

    private static boolean isReflectionFrame(Class<?> c) {
        String n = c.getName();
        return c == java.lang.reflect.Method.class || c == java.lang.reflect.Constructor.class
                || n.startsWith("jdk.internal.reflect.");
    }

    private static boolean isHiddenFrame(Class<?> c) {
        String n = c.getName();
        return n.contains("$$Lambda") || n.contains("$$MONO") || n.startsWith("jdk.proxy.$MonoProxy")
                || n.startsWith("java.lang.invoke.MonoMH") || c == java.lang.invoke.MethodHandle.class;
    }

    private List<StackFrame> frames(boolean forCaller) {
        Object[] raw = frames0();
        Class<?>[] cs = (Class<?>[]) raw[0];
        String[] ns = (String[]) raw[1];
        String[] ds = (String[]) raw[2];
        String[] fs = (String[]) raw[3];
        int[] ls = (int[]) raw[4];
        List<StackFrame> out = new ArrayList<>(cs.length);
        int i = 0;
        while (i < cs.length && cs[i] != null && cs[i].getName().startsWith("java.lang.StackWalker")) i++;
        boolean showHidden = !forCaller && options.contains(Option.SHOW_HIDDEN_FRAMES);
        boolean showReflect = !forCaller && (showHidden || options.contains(Option.SHOW_REFLECT_FRAMES));
        for (; i < cs.length; i++) {
            Class<?> c = cs[i];
            if (c == null) continue;
            if (!showReflect && isReflectionFrame(c)) continue;
            if (!showHidden && isHiddenFrame(c)) continue;
            out.add(new Frame(this, c, ns[i], ds[i], fs[i], ls[i]));
        }
        return out;
    }

    public <T> T walk(Function<? super Stream<StackFrame>, ? extends T> function) {
        Objects.requireNonNull(function);
        return function.apply(frames(false).stream());
    }

    public void forEach(Consumer<? super StackFrame> action) {
        Objects.requireNonNull(action);
        frames(false).forEach(action);
    }

    public Class<?> getCallerClass() {
        if (!retainClassRef) throw new UnsupportedOperationException("This stack walker does not have RETAIN_CLASS_REFERENCE access");
        List<StackFrame> f = frames(true);
        // f[0] is the method that called getCallerClass; its caller is f[1]
        if (f.size() < 2) throw new IllegalCallerException("no caller frame");
        return f.get(1).getDeclaringClass();
    }
}
