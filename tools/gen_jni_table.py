#!/usr/bin/env python3
"""Regenerate runtime/jni_table.zig (JNIEnv function-table order) from the JDK's jni.h."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from j2zig.classpath import jdk_home  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    s = open(os.path.join(jdk_home(), "include", "jni.h")).read()
    i = s.index("struct JNINativeInterface_ {")
    body = s[i:s.index("};", i)]
    names = []
    for m in re.finditer(r"(void \*reserved\d)|\(JNICALL \*(\w+)\)", body):
        names.append(m.group(1).split()[-1].lstrip("*") if m.group(1) else m.group(2))
    out = ["//! GENERATED by tools/gen_jni_table.py from the JDK's include/jni.h — do not edit.\n",
           "//! Order of the JNINativeInterface_ function table (JNIEnv).\n",
           f"pub const count = {len(names)};\n", "pub const names = [_][]const u8{\n"]
    out += [f'    "{n}",\n' for n in names]
    out.append("};\n")
    with open(os.path.join(ROOT, "runtime", "jni_table.zig"), "w") as fh:
        fh.write("".join(out))


if __name__ == "__main__":
    main()
